/**
 * Netlify rules for the Pulse Driver web app at /driver (driver extraction Phase 4A).
 * Written to dist/_redirects and appended to dist/_headers by scripts/build-ci.js, ONLY
 * when EXPO_PUBLIC_DRIVER_APP_EXTRACTION_ENABLED=true (preprod). Netlify applies
 * _redirects before netlify.toml, so these win over the main app's `/*` catch-all.
 *
 * Route collision: `/driver/<uuid>` was the dispatcher driver-detail URL (now
 * /fleet-driver/<uuid>). Netlify placeholders cannot match "UUID only", so every real
 * driver-app path is listed explicitly (generated from apps/driver/app, never by hand)
 * and any OTHER single-segment `/driver/<x>` gets a 301 to /fleet-driver/<x>. A
 * dispatcher link therefore never loads the driver app.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const APP_DIR = path.join(__dirname, '..', 'apps', 'driver', 'app');
const NON_ROUTE = /^(_layout|\+not-found|\+html|loading)$/;

/** First URL segments of the driver app's routes; `nested` = has deeper routes. */
function driverRootSegments(appDir = APP_DIR) {
  const segs = new Map();
  const walk = (dir, parts) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) { walk(path.join(dir, e.name), [...parts, e.name]); continue; }
      if (!/\.(tsx?|jsx?)$/.test(e.name)) continue;
      const name = e.name.replace(/(\.(web|native|ios|android))?\.(tsx?|jsx?)$/, '');
      if (NON_ROUTE.test(name)) continue;
      const url = [...parts, name].filter((s) => !/^\(.*\)$/.test(s) && s !== 'index');
      if (!url.length) continue; // the app root: /driver
      if (/^\[.*\]$/.test(url[0])) throw new Error(`dynamic first segment in apps/driver/app: ${url[0]}`);
      segs.set(url[0], (segs.get(url[0]) ?? false) || url.length > 1);
    }
  };
  walk(appDir, []);
  return new Map([...segs].sort(([a], [b]) => a.localeCompare(b)));
}

function driverRedirects(appDir = APP_DIR) {
  const SPA = '/driver/index.html';
  const lines = [
    '# Pulse Driver web app (generated by scripts/driver-web-redirects.js — do not edit)',
    `/driver/_expo/static/*  ${SPA}  404`,
    `/driver  ${SPA}  200`,
  ];
  for (const [seg, nested] of driverRootSegments(appDir)) {
    lines.push(`/driver/${seg}  ${SPA}  200`);
    if (nested) lines.push(`/driver/${seg}/*  ${SPA}  200`);
  }
  lines.push(
    '# Legacy dispatcher driver-detail links → /fleet-driver (never the driver app)',
    '/driver/:id/analytics  /fleet-driver/:id/analytics  301',
    '/driver/:id/profile  /fleet-driver/:id/profile  301',
    '/driver/:id  /fleet-driver/:id  301',
    `/driver/*  ${SPA}  200`,
  );
  return `${lines.join('\n')}\n`;
}

function driverHeaders() {
  return [
    '',
    '# Pulse Driver web app (scripts/driver-web-redirects.js)',
    '/driver',
    '  Cache-Control: no-cache, no-store, must-revalidate',
    '/driver/',
    '  Cache-Control: no-cache, no-store, must-revalidate',
    '/driver/index.html',
    '  Cache-Control: no-cache, no-store, must-revalidate',
    '/driver/_expo/static/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ].join('\n');
}

module.exports = { driverRootSegments, driverRedirects, driverHeaders };

if (require.main === module) process.stdout.write(driverRedirects());
